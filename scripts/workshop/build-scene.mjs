#!/usr/bin/env node
// Writes hooks/workshop/scene-data.ts, the workshop pane's static drawing, from what
// docs/mod/workshop/gen.py draws: the room for each stage of the mech (scene.svg, then
// mecha/scene_stage1..4.svg) and the light layers (lights/*.svg).
// One Svg holds at most 128 KB and the room alone shrinks to about 110, so each room is cut
// at SPLIT into two strips, each shrunk on its own; the pane stacks them without a gap.
// Run after gen.py: python docs/mod/workshop/gen.py && node scripts/workshop/build-scene.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { minify } from './svgmin.mjs'

const root = resolve(dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../..')
const SRC = join(root, 'docs/mod/workshop')
const OUT = join(root, 'hooks/workshop/scene-data.ts')
const read = (p) => readFileSync(p, 'utf8')

const FULL = read(join(SRC, 'scene.svg')).match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number)
const [X, Y, W, H] = FULL
const SPLIT = Y + Math.round(H / 2)
const STRIPS = [[X, Y, W, SPLIT - Y], [X, SPLIT, W, Y + H - SPLIT]]
const pack = (m) => ({ css: m.css, defs: m.defs, body: m.body })

// The room, one per mech stage (0 is the empty bay), each in its two strips.
const rooms = [join(SRC, 'scene.svg'), ...[1, 2, 3, 4].map((n) => join(SRC, `mecha/scene_stage${n}.svg`))]
const SCENES = rooms.map((f) => { const svg = read(f); return STRIPS.map((clip) => pack(minify(svg, { Q: 1, step: 6, clip, prefix: 'a' }))) })

// The lights: gen.py's radial pools and halos share one gradient per colour, their strength
// in fill-opacity; the geometry a light carries (the hologram, the sirens) is shrunk as the room is.
const grads = new Map()
const gid = (c) => { if (!grads.has(c)) grads.set(c, `L${grads.size}`); return grads.get(c) }
const LIGHTS = {}
for (const f of readdirSync(join(SRC, 'lights')).sort()) {
  const name = f.replace('.svg', '')
  const svg = read(join(SRC, 'lights', f))
  const stops = {}
  for (const m of svg.matchAll(/<radialGradient id="([^"]+)"><stop offset="0" stop-color="([^"]+)" stop-opacity="([^"]+)"/g)) stops[m[1]] = [m[2], +m[3]]
  let glows = ''
  for (const m of svg.matchAll(/<(ellipse|circle) ([^>]*)\/>/g)) {
    const a = Object.fromEntries([...m[2].matchAll(/([a-z]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]))
    const g = stops[a.fill?.slice(5, -1)]
    if (!g) continue
    const r = (v) => Math.round(+v)
    const op = +g[1].toFixed(2)
    glows += m[1] === 'circle'
      ? `<circle cx="${r(a.cx)}" cy="${r(a.cy)}" r="${r(a.r)}" fill="url(#${gid(g[0])})" fill-opacity="${op}"/>`
      : `<ellipse cx="${r(a.cx)}" cy="${r(a.cy)}" rx="${r(a.rx)}" ry="${r(a.ry)}" fill="url(#${gid(g[0])})" fill-opacity="${op}"/>`
  }
  const veil = svg.match(/<rect [^>]*fill="(#[0-9a-f]+)" fill-opacity="([^"]+)"/)
  if (veil) glows += `<rect x="${X}" y="${Y}" width="${W}" height="${H}" fill="${veil[1]}" fill-opacity="${veil[2]}"/>`
  const geo = /<(polygon|polyline|line) /.test(svg) ? pack(minify(svg, { Q: 1, step: 0, doCull: false, prefix: 'L' + name.slice(0, 2) })) : null
  LIGHTS[name] = { glows, geo }
}
const LIGHT_DEFS = [...grads].map(([c, id]) => `<radialGradient id="${id}"><stop offset="0" stop-color="${c}"/><stop offset=".35" stop-color="${c}" stop-opacity=".55"/><stop offset=".7" stop-color="${c}" stop-opacity=".18"/><stop offset="1" stop-color="${c}" stop-opacity="0"/></radialGradient>`).join('')

const j = (v) => JSON.stringify(v)
writeFileSync(OUT, `// Generated by scripts/workshop/build-scene.mjs from docs/mod/workshop (gen.py's drawing): do not edit.
// A strip is one Svg's share of the room: its class rules, its gradients and its paths.
export type Strip = { css: string; defs: string; body: string }
export type Light = { glows: string; geo: Strip | null }

/** The room's viewBox in gen.py's units: x, y, width, height. */
export const FULL: readonly [number, number, number, number] = ${j(FULL)}
/** The y the two strips meet at. */
export const SPLIT = ${SPLIT}
/** The room at each mech stage, 0 (an empty bay) to 4 (the whole mech), as its two strips. */
export const SCENES: Strip[][] = ${j(SCENES)}
/** Each light layer by gen.py's name: the glows, and what geometry it lights up. */
export const LIGHTS: Record<string, Light> = ${j(LIGHTS)}
/** The light gradients, one per colour, that LIGHTS' glows fill with. */
export const LIGHT_DEFS = ${j(LIGHT_DEFS)}
`)
const kb = (s) => (j(s).length / 1024).toFixed(1)
console.log(`wrote hooks/workshop/scene-data.ts, split at y=${SPLIT}`)
SCENES.forEach((s, i) => console.log(`  stage ${i}: ${kb(s[0])} + ${kb(s[1])} KB`))
